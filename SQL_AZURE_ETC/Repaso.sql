CREATE FUNCTION dbo.fn_EstadoNota
(
    @NOTA DECIMAL(5,2)
)
RETURNS VARCHAR(20)
AS
BEGIN

    DECLARE @ESTADO VARCHAR(20);

    IF @NOTA >= 3
        SET @ESTADO = 'APROBO';
    ELSE
        SET @ESTADO = 'REPROBO';

    RETURN @ESTADO;

END;